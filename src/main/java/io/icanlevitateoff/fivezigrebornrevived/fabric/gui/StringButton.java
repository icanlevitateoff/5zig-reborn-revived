package io.icanlevitateoff.fivezigrebornrevived.fabric.gui;

/** A button drawn as plain text (no background). */
public class StringButton extends Button {

	public StringButton(int id, int x, int y, String label) {
		super(id, x, y, label);
	}

	public StringButton(int id, int x, int y, int width, int height, String label) {
		super(id, x, y, width, height, label);
	}

	@Override
	public void draw(int mouseX, int mouseY) {
		if (!isVisible()) {
			return;
		}
		setHovered(isMouseOver(mouseX, mouseY));
		drawLabel(!isEnabled() ? 0xFFA0A0A0 : isHovered() ? 0xFFFFFFA0 : 0xFFE0E0E0);
	}
}
